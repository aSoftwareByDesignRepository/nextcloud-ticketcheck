<?php

declare(strict_types=1);

namespace OCA\Ticketcheck\Tests\Unit;

use OCA\Ticketcheck\Service\InboundMailClassifier;
use PHPUnit\Framework\TestCase;

class InboundMailClassifierTest extends TestCase
{
	// ---------- msgHash ----------

	public function testMsgHashUsesMessageIdPlusSender(): void
	{
		$a = InboundMailClassifier::msgHash('<abc@x>', 'Sender@Example.com', 's', '2026-01-01', 5);
		$b = InboundMailClassifier::msgHash('<ABC@X>', 'sender@example.com', 'different', 'other', 99);
		// Case-insensitive mid+from; subject/uid must not matter when Message-ID exists.
		self::assertSame($a, $b);
	}

	public function testMsgHashDiffersForDifferentSendersWithSameMessageId(): void
	{
		$a = InboundMailClassifier::msgHash('<shared@x>', 'a@example.com', 's', null, 0);
		$b = InboundMailClassifier::msgHash('<shared@x>', 'b@example.com', 's', null, 0);
		self::assertNotSame($a, $b, 'sender-bound hash prevents pre-claiming a victim Message-ID');
	}

	public function testMsgHashFallbackWhenNoMessageId(): void
	{
		$a = InboundMailClassifier::msgHash(null, 'a@example.com', 'Hello', '2026-01-01', 7);
		$b = InboundMailClassifier::msgHash('', 'a@example.com', 'Hello', '2026-01-01', 7);
		self::assertSame($a, $b);
		$c = InboundMailClassifier::msgHash(null, 'a@example.com', 'Hello', '2026-01-01', 8);
		self::assertNotSame($a, $c, 'uid separates otherwise identical fallback mails');
	}

	// ---------- isAutomated ----------

	public function testIsAutomatedDetectsAutoSubmittedHeader(): void
	{
		$msg = ['from' => 'bob@example.com', 'subject' => 'hi', 'rawHeader' => "Auto-Submitted: auto-replied\r\nFrom: bob@example.com"];
		self::assertTrue(InboundMailClassifier::isAutomated($msg, 'support@example.com'));
	}

	public function testIsAutomatedDetectsAutoGenerated(): void
	{
		$msg = ['from' => 'bob@example.com', 'subject' => 'hi', 'rawHeader' => "Auto-Submitted: auto-generated\r\n"];
		self::assertTrue(InboundMailClassifier::isAutomated($msg, 'support@example.com'));
	}

	public function testIsAutomatedDaemonPrefixes(): void
	{
		foreach (['mailer-daemon@example.com', 'postmaster@example.com', 'hostmaster@example.com', 'noreply-daemon@example.com'] as $from) {
			self::assertTrue(InboundMailClassifier::isAutomated(['from' => $from, 'subject' => 'x'], 'support@example.com'), $from);
		}
		// Plain noreply@ is NOT auto-classified — monitoring alerts to noreply@
		// are legitimate ticket sources.
		self::assertFalse(InboundMailClassifier::isAutomated(['from' => 'noreply@example.com', 'subject' => 'x'], 'support@example.com'));
	}

	public function testIsAutomatedSelfMail(): void
	{
		$msg = ['from' => 'Support@Example.com', 'subject' => 'loop'];
		self::assertTrue(InboundMailClassifier::isAutomated($msg, 'support@example.com'));
	}

	public function testIsAutomatedEmptyReturnPath(): void
	{
		$msg = ['from' => 'bob@example.com', 'subject' => 'bounce', 'rawHeader' => "Return-Path: <>\r\nFrom: bob@example.com"];
		self::assertTrue(InboundMailClassifier::isAutomated($msg, 'support@example.com'));
	}

	public function testIsAutomatedListHeaders(): void
	{
		$msg = ['from' => 'bob@example.com', 'subject' => 'list', 'rawHeader' => "List-Id: <list.example.com>\r\n"];
		self::assertTrue(InboundMailClassifier::isAutomated($msg, 'support@example.com'));
	}

	public function testIsAutomatedPrecedenceJunk(): void
	{
		$msg = ['from' => 'bob@example.com', 'subject' => 'x', 'rawHeader' => "Precedence: bulk\r\n"];
		self::assertTrue(InboundMailClassifier::isAutomated($msg, 'support@example.com'));
	}

	public function testIsAutomatedFalseForNormalMail(): void
	{
		$msg = ['from' => 'customer@example.com', 'subject' => 'Question', 'rawHeader' => "From: customer@example.com\r\nSubject: Question\r\n"];
		self::assertFalse(InboundMailClassifier::isAutomated($msg, 'support@example.com'));
	}

	public function testIsAutomatedAutoreplyHeaders(): void
	{
		foreach (['X-Autoreply: yes', 'X-Autorespond: yes', 'X-Auto-Response-Suppress: All'] as $h) {
			$msg = ['from' => 'c@example.com', 'subject' => 'x', 'rawHeader' => $h . "\r\n"];
			self::assertTrue(InboundMailClassifier::isAutomated($msg, 'support@example.com'), $h);
		}
	}

	// ---------- extractReplyTarget ----------

	public function testExtractReplyTargetTokenized(): void
	{
		$target = InboundMailClassifier::extractReplyTarget(['support+42-abcdef0123@example.com'], 'support@example.com');
		self::assertSame(['id' => 42, 'token' => 'abcdef0123', 'legacy' => false], $target);
	}

	public function testExtractReplyTargetLegacy(): void
	{
		$target = InboundMailClassifier::extractReplyTarget(['support+7@example.com'], 'support@example.com');
		self::assertSame(['id' => 7, 'token' => null, 'legacy' => true], $target);
	}

	public function testExtractReplyTargetFromCc(): void
	{
		$target = InboundMailClassifier::extractReplyTarget(
			['someone@example.com', 'support+9-deadbeef00@example.com'],
			'support@example.com'
		);
		self::assertSame(9, $target['id']);
		self::assertSame('deadbeef00', $target['token']);
	}

	public function testExtractReplyTargetIgnoresWrongDomain(): void
	{
		self::assertNull(InboundMailClassifier::extractReplyTarget(['support+5@evil.com'], 'support@example.com'));
	}

	public function testExtractReplyTargetIgnoresWrongLocalPart(): void
	{
		self::assertNull(InboundMailClassifier::extractReplyTarget(['billing+5@example.com'], 'support@example.com'));
	}

	public function testExtractReplyTargetIgnoresMalformedToken(): void
	{
		// Token must be exactly 10 lowercase hex chars.
		self::assertNull(InboundMailClassifier::extractReplyTarget(['support+5-XYZ@example.com'], 'support@example.com'));
		// support+5-XYZ is not a valid +{id} or +{id}-{token} shape → no target.
		self::assertNull(InboundMailClassifier::extractReplyTarget(['support+5-abcdef01234@example.com'], 'support@example.com'));
	}

	public function testExtractReplyTargetZeroIdRejected(): void
	{
		self::assertNull(InboundMailClassifier::extractReplyTarget(['support+0@example.com'], 'support@example.com'));
	}

	public function testExtractReplyTargetEmptyInboundAddress(): void
	{
		self::assertNull(InboundMailClassifier::extractReplyTarget(['support+5@example.com'], ''));
	}

	// ---------- extractSubjectTicketId ----------

	public function testExtractSubjectTicketId(): void
	{
		self::assertSame(12, InboundMailClassifier::extractSubjectTicketId('Re: Ticket #12'));
		self::assertSame(34, InboundMailClassifier::extractSubjectTicketId('ticket 34 follow-up'));
		self::assertSame(5, InboundMailClassifier::extractSubjectTicketId('Re: #5 fixed?'));
		self::assertNull(InboundMailClassifier::extractSubjectTicketId('No number here'));
		self::assertNull(InboundMailClassifier::extractSubjectTicketId('#0'));
	}

	// ---------- routingTarget ----------

	private function map(): array
	{
		return [
			'billing' => ['project_id' => 2, 'category' => 'finance'],
			'alias@example.com' => ['project_id' => 3, 'category' => ''],
			'helpdesk' => ['project_id' => null, 'category' => 'urgent'],
		];
	}

	public function testRoutingTargetNamedPlusTag(): void
	{
		$t = InboundMailClassifier::routingTarget(['support+billing@example.com'], 'support@example.com', $this->map());
		self::assertSame(['project_id' => 2, 'category' => 'finance'], $t);
	}

	public function testRoutingTargetFullAlias(): void
	{
		$t = InboundMailClassifier::routingTarget(['alias@example.com'], 'support@example.com', $this->map());
		self::assertSame(['project_id' => 3, 'category' => ''], $t);
	}

	public function testRoutingTargetLocalPart(): void
	{
		$t = InboundMailClassifier::routingTarget(['helpdesk@example.com'], 'support@example.com', $this->map());
		self::assertSame(['project_id' => null, 'category' => 'urgent'], $t);
	}

	public function testRoutingTargetNumericTagIsNotRouting(): void
	{
		// support+5@ is a ticket reply address, never a routing key.
		$map = ['5' => ['project_id' => 9, 'category' => 'x']];
		self::assertNull(InboundMailClassifier::routingTarget(['support+5@example.com'], 'support@example.com', $map));
	}

	public function testRoutingTargetEmptyMap(): void
	{
		self::assertNull(InboundMailClassifier::routingTarget(['support+billing@example.com'], 'support@example.com', []));
	}

	public function testRoutingTargetNoMatch(): void
	{
		$t = InboundMailClassifier::routingTarget(['someone@other.com'], 'support@example.com', $this->map());
		self::assertNull($t);
	}

	// ---------- trimQuotedText / normalizeBody ----------

	public function testTrimQuotedTextStripsTrailingQuote(): void
	{
		$text = "My reply here\n\nOn Mon, Bob wrote:\n> original line\n> more original";
		self::assertSame('My reply here', trim(InboundMailClassifier::trimQuotedText($text)));
	}

	public function testTrimQuotedTextKeepsMiddleQuotes(): void
	{
		$text = "First\n> quoted bit in middle\nSecond line after";
		self::assertStringContainsString('Second line after', InboundMailClassifier::trimQuotedText($text));
	}

	public function testNormalizeBodyPrefersText(): void
	{
		self::assertSame('plain body', InboundMailClassifier::normalizeBody('plain body', '<b>html</b>'));
	}

	public function testNormalizeBodyStripsHtml(): void
	{
		$out = InboundMailClassifier::normalizeBody('', '<p>Hello <b>world</b></p>');
		self::assertStringContainsString('Hello', $out);
		self::assertStringContainsString('world', $out);
		self::assertStringNotContainsString('<b>', $out);
	}

	public function testNormalizeBodyCapsLength(): void
	{
		$out = InboundMailClassifier::normalizeBody(str_repeat('x', 50000), '', 1000);
		self::assertLessThanOrEqual(1000, strlen($out));
	}

	public function testNormalizeBodyTruncationMarkerSurvivesSignatureStrip(): void
	{
		// Regression (tkc-imap-body-truncation-marker-missing): a "--"
		// signature within the last 8 lines of the TRUNCATED text used to eat
		// the appended marker — truncated mail showed no "[…gekürzt]".
		$body = str_repeat('y', 900) . "\n--\n" . str_repeat('z', 5000);
		$out = InboundMailClassifier::normalizeBody($body, '', 1000);
		self::assertStringContainsString('[…gekürzt]', $out);
		self::assertStringEndsWith('[…gekürzt]', $out);
		self::assertLessThanOrEqual(1000, strlen($out));
	}

	// ---------- sanitizeFilename ----------

	public function testSanitizeFilename(): void
	{
		self::assertSame('report.pdf', InboundMailClassifier::sanitizeFilename('report.pdf'));
		self::assertSame('passwd', InboundMailClassifier::sanitizeFilename('../etc/passwd'));
		self::assertSame('b.txt', InboundMailClassifier::sanitizeFilename('a\\b.txt'));
		// Unusable names return '' — the caller defaults them.
		self::assertSame('', InboundMailClassifier::sanitizeFilename(''));
		self::assertSame('', InboundMailClassifier::sanitizeFilename('.'));
		self::assertSame('', InboundMailClassifier::sanitizeFilename('..'));
	}
}
